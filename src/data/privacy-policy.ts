/** 条項本文を構成するブロック（判別ユニオン） */
export type PrivacyBlock =
  // 段落群: 各要素を 1 つの <p>（強制改行）として縦に積む
  | { type: 'text'; paragraphs: readonly string[] }
  // リスト: 先頭のリード文 + 箇条書き。ordered=true で番号付き、false で「・」
  | { type: 'list'; ordered: boolean; lead: string; items: readonly string[] }
  // 連絡先: リード文 + 社名 / 所在地 / メール（mailto リンク）
  | {
      type: 'contact';
      lead: string;
      name: string;
      address: string;
      emailPrefix: string;
      email: string;
    };

export type PrivacySection = {
  /** 見出し（番号込み）。例: "1. 取得する情報" */
  heading: string;
  block: PrivacyBlock;
};

